function id(kind, sourceId) {
  if (kind === 'user' && sourceId === 'u0') return viewer;
  const hash = crypto.createHash('md5').update(`worldlearn-demo:${kind}:${sourceId}`).digest('hex');
  return `${hash.slice(0,8)}-${hash.slice(8,12)}-${hash.slice(12,16)}-${hash.slice(16,20)}-${hash.slice(20)}`;
}
const raw = (sql) => ({ sql });
function value(v) {
  if (v === undefined || v === null) return 'NULL';
  if (typeof v === 'object') return v.sql;
  if (typeof v !== 'string') return String(v);
  return `'${v.replaceAll("'", "''")}'`;
}
const country = (code) => raw(`(SELECT id FROM country WHERE iso_code=${value(code)})`);
const field = (label) => raw(`(SELECT id FROM field WHERE label=${value(label)})`);
const status = (table, label) => raw(`(SELECT id FROM ${table} WHERE label=${value(label)})`);
const ago = (hours) => raw(`now()-interval '${hours} hours'`);
function statement(table, columns, rows, conflict = 'ON CONFLICT DO NOTHING') {
  return `INSERT INTO ${table} (${columns.join(',')}) VALUES\n` +
    rows.map((row) => `  (${row.map(value).join(',')})`).join(',\n') + `\n${conflict}`;
}
